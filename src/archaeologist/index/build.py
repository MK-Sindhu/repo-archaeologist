FILE_SKIP_REASONS = ("excluded", "binary", "too_large", "generated", "unreadable")

_GENERATED_MARK = re.compile(
    r"@generated|DO NOT EDIT|auto-?generated by|automatically generated", re.IGNORECASE
)
_COMMENT_START = ("#", "//", "/*", "*", "<!--", "--", ";", '"""', "'''")
_DOC_EXTS = MARKDOWN_EXTS | RST_EXTS | PLAIN_DOC_EXTS
_MINIFIED_AVG_LINE = 300

ProgressFn = Callable[[str, int, int | None], None]


class RepoLike(Protocol):
    """The parts of `sources.git.GitRepo` that `build_index` uses.

    A repository may also offer `file_sizes() -> dict[str, int]` (blob sizes at HEAD, as
    GitRepo does): files over `max_file_bytes` are then skipped without being read.
    """

    def head_sha(self) -> str | None: ...

    def ls_files(self) -> list[str]: ...

    def read_file(self, path: str) -> str | None: ...  # None: missing or binary

    def iter_commits(self, max_count: int | None = None) -> Iterator[CommitLike]: ...


# -- file filters ----------------------------------------------------------------------------


def is_included(path: str, include: Iterable[str] = DEFAULT_INCLUDE) -> bool:
    """True if the file's extension (".py", case-insensitive) or exact name ("Makefile") is in
    `include`."""
    p = PurePosixPath(path)
    suffix = p.suffix.lower()
    for pat in include:
        if pat.startswith(".") and suffix == pat.lower():
            return True
        if not pat.startswith(".") and p.name == pat:
            return True
    return False


def is_excluded(path: str, exclude: Iterable[str] = DEFAULT_EXCLUDE) -> bool:
    """True if `path` matches an exclude pattern.

    "name/" matches a directory of that name anywhere, "/name/" only at the repo root, and
    any other pattern is a glob matched against the file name and the full path.
    """
    p = PurePosixPath(path)
    dirs = p.parts[:-1]
    for pat in exclude:
        if pat.endswith("/"):
            name = pat.strip("/")
            candidates = dirs[:1] if pat.startswith("/") else dirs
            if any(fnmatch(d, name) for d in candidates):
                return True
        elif fnmatch(p.name, pat) or fnmatch(path, pat):
            return True
    return False


def _looks_binary(text: str) -> bool:
    if "\x00" in text:
        return True
    sample = text[:8192]
    return bool(sample) and sample.count("\N{REPLACEMENT CHARACTER}") > len(sample) * 0.05


def _looks_generated(path: str, text: str) -> bool:
    """Generated-file markers in leading comment lines, or minified (very long lines) code."""
    head = text[:4096].splitlines()[:8]
    for line in head:
        s = line.lstrip()
        if s.startswith(_COMMENT_START) and _GENERATED_MARK.search(s):
            return True
    if PurePosixPath(path).suffix.lower() in _DOC_EXTS:
        return False
    n_lines = text.count("\n") + 1
    return len(text) > 2000 and len(text) / n_lines > _MINIFIED_AVG_LINE


# -- build -----------------------------------------------------------------------------------


def _fingerprint(
    include: tuple[str, ...], exclude: tuple[str, ...], max_file_bytes: int, max_commits: int | None
) -> str:
    spec = {
        "chunker": CHUNKER_VERSION,
        "include": sorted(include),
        "exclude": sorted(exclude),
        "max_file_bytes": max_file_bytes,
        "max_commits": max_commits,
    }
    return hashlib.sha1(json.dumps(spec, sort_keys=True).encode()).hexdigest()


def _stats(index: HybridIndex, head: str | None, skipped: bool) -> dict[str, Any]:
    stats: dict[str, Any] = {"skipped": skipped, "head_sha": head}
    stats.update({kind: index.count(kind) for kind in KINDS})
    stats["added"] = dict.fromkeys(KINDS, 0)
    stats["removed"] = 0
    stats["files"] = dict.fromkeys(("indexed", "unchanged", *FILE_SKIP_REASONS), 0)
    stats["commits"] = 0
    return stats


class _Writer:
    """Buffers chunk upserts so the embedder sees reasonably sized batches."""

    def __init__(self, index: HybridIndex, batch_size: int, added: dict[str, int]):
        self.index = index
        self.batch_size = batch_size
        self.added = added
        self.buffer: list[Chunk] = []

    def put(self, chunks: Iterable[Chunk]) -> None:
        self.buffer.extend(chunks)
        if len(self.buffer) >= self.batch_size:
            self.flush()

    def flush(self) -> None:
        if not self.buffer:
            return
        self.index.add(self.buffer)
        for c in self.buffer:
            self.added[c.kind] += 1
        self.buffer = []


def build_index(
    repo: RepoLike,
    index: HybridIndex,
    max_commits: int | None = 5000,
    max_file_bytes: int = 200_000,
    include: Iterable[str] = DEFAULT_INCLUDE,
    exclude: Iterable[str] = DEFAULT_EXCLUDE,
    *,
    force: bool = False,
    workers: int = 8,
    batch_size: int = 256,
    progress: ProgressFn | None = None,
) -> dict[str, Any]:
    """Index code and docs at HEAD and the newest `max_commits` commit messages.

    Skipped files: not matching `include`, matching `exclude` (vendored dirs, lockfiles,
    minified/generated files), binary, larger than `max_file_bytes`, carrying a
    generated-code marker, or unreadable (`read_file` raised or returned None, which GitRepo
    does for binary blobs). Files are read with `workers` threads.

    Incremental: if the index's ``head_sha`` meta equals ``repo.head_sha()`` (and the build
    settings are unchanged, and not `force`) it returns at once with ``skipped=True``.
    Otherwise unchanged files keep their chunks, changed files are re-chunked, chunks of
    files no longer indexed are removed, and commits already indexed are not re-embedded.

    Returns stats: ``skipped``, ``head_sha``, chunk totals per kind (``code``, ``doc``,
    ``commit``), ``added`` per kind, ``removed``, per-reason file counts in ``files``, and
    ``commits`` seen.
    """
    include_t, exclude_t = tuple(include), tuple(exclude)
    batch_size, workers = max(1, batch_size), max(1, workers)
    head = repo.head_sha() or None
    fingerprint = _fingerprint(include_t, exclude_t, max_file_bytes, max_commits)
    unchanged_build = index.get_meta("build_fingerprint") == fingerprint
    if not force and head is not None and unchanged_build and index.get_meta("head_sha") == head:
        return _stats(index, head, skipped=True)

    stats = _stats(index, head, skipped=False)
    if head is None:  # empty repository: nothing at HEAD yet
        return stats
    files = stats["files"]
    writer = _Writer(index, batch_size, stats["added"])
    full = force or not unchanged_build

    # -- files at HEAD ---------------------------------------------------------------------
    old_hashes: dict[str, str] = {}
    if not full:
        old_hashes = json.loads(index.get_meta("file_hashes") or "{}")
    indexed_paths = index.ids_by_path(("code", "doc"))
    sizes_fn = getattr(repo, "file_sizes", None)
    sizes: dict[str, int] = sizes_fn() if callable(sizes_fn) else {}
    candidates = []
    for path in repo.ls_files():
        if not is_included(path, include_t) or is_excluded(path, exclude_t):
            files["excluded"] += 1
        elif sizes.get(path, 0) > max_file_bytes:  # skip big blobs without reading them
            files["too_large"] += 1
        else:
            candidates.append(path)

    def read(path: str) -> tuple[str, str | None]:
        try:
            return path, repo.read_file(path)
        except Exception as e:  # noqa: BLE001 - any repo error (missing blob, decode) skips it
            logger.debug("cannot read %s: %s", path, e)
            return path, None

    new_hashes: dict[str, str] = {}
    stale: set[str] = set()
    window = workers * 8
    with ThreadPoolExecutor(max_workers=workers) as pool:
        for start in range(0, len(candidates), window):
            for path, text in pool.map(read, candidates[start : start + window]):
                if text is None:
                    files["unreadable"] += 1
                    continue
                if len(text.encode("utf-8", errors="replace")) > max_file_bytes:
                    files["too_large"] += 1
                    continue
                if _looks_binary(text):
                    files["binary"] += 1
                    continue
                if _looks_generated(path, text):
                    files["generated"] += 1
                    continue
                digest = hashlib.sha1(text.encode("utf-8", errors="replace")).hexdigest()
                new_hashes[path] = digest
                old_ids = indexed_paths.get(path, set())
                if old_hashes.get(path) == digest:
                    files["unchanged"] += 1
                    continue
                chunks = chunk_file(path, text)
                stale |= old_ids - {c.id for c in chunks}
                writer.put(chunks)
                files["indexed"] += 1
            if progress:
                progress("files", min(start + window, len(candidates)), len(candidates))
    for path, ids in indexed_paths.items():
        if path not in new_hashes:
            stale |= ids
    writer.flush()
    stats["removed"] += index.delete(stale)

    # -- commits ---------------------------------------------------------------------------
    existing = set() if full else index.ids("commit")
    seen: set[str] = set()
    if max_commits is None or max_commits > 0:
        for commit in repo.iter_commits(max_count=max_commits):
            cid = commit_ref(commit.sha)
            if cid in seen:
                continue
            seen.add(cid)
            if cid not in existing:
                writer.put([commit_chunk(commit)])
            if progress and len(seen) % batch_size == 0:
                progress("commits", len(seen), max_commits)
    writer.flush()
    stats["commits"] = len(seen)
    stats["removed"] += index.delete(index.ids("commit") - seen)
    if progress:
        progress("commits", len(seen), len(seen))

    index.set_meta("file_hashes", json.dumps(new_hashes, sort_keys=True))
    index.set_meta("build_fingerprint", fingerprint)
    index.set_meta("built_at", datetime.now(UTC).isoformat(timespec="seconds"))
    index.set_meta("head_sha", head)
    stats.update({kind: index.count(kind) for kind in KINDS})
    return stats
