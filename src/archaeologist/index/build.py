"""Build or refresh a `HybridIndex` from a git repository: code and docs at HEAD plus commit
messages.

The repository is duck-typed (`RepoLike`); `archaeologist.sources.git.GitRepo` satisfies it.
Rebuilds are incremental: when HEAD and the build settings are unchanged nothing is done,
otherwise only files whose content changed are re-chunked (and re-embedded), chunks of
deleted or newly excluded files are removed, and only new commits are added.
"""

